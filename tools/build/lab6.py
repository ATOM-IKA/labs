CODE = f"{FOLDER}/room_area.py"

spec = importlib.util.spec_from_file_location("room_area", CODE)
room = importlib.util.module_from_spec(spec)
spec.loader.exec_module(room)

NUM = "Ошибка: нужно ввести число"
RNG = "Ошибка: размер должен быть от 0.1 до 100 м"


def call(length, width):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        value = room.room_area(length, width)
    return value, buf.getvalue().strip()


def fmt_call(value, text):
    return text if value is None else str(value)


def console(answers):
    out = echo_run(CODE, answers)
    return out


cases = []
for kind, title, args, expected in [
    ("Позитивный", "длина 4, ширина 5", ("4", "5"), "20.0"),
    ("Позитивный", "длина 4,5, ширина 3", ("4,5", "3"), "13.5"),
]:
    value, text = call(*args)
    cases.append((kind, title, expected, fmt_call(value, text)))

out = console(["4", "3", "2", "2", ""])
