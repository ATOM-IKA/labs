def pages(path):
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", SCRATCH, path], capture_output=True)
    pdf = path.rsplit("/", 1)[1].replace(".docx", ".pdf")
    info = subprocess.run(["pdfinfo", f"{SCRATCH}/{pdf}"], capture_output=True, text=True).stdout
    return int(next(line for line in info.splitlines() if line.startswith("Pages:")).split()[1])


