def ok_value(fn, expected):
    def run():
        got = fn()
        return got == expected, f"{got:.2f} м²" if isinstance(got, float) else str(got)
    return run


def rejects(fn, fragment):
    def run():
        try:
            return False, f"принято, результат {fn()}"
        except InputError as e:
            return fragment in str(e), f"«{e}»"
    return run


def cli(stdin, fragment):
    def run():
        out = subprocess.run([sys.executable, "/root/labs/labs/lab6/src/room_area.py"], input=stdin,
                             capture_output=True, text=True).stdout.splitlines()[-1]
        for mark in ("Площадь помещения: ", "Ошибка: "):
            if mark in out:
                out = out[out.index(mark):]
        return fragment in out, f"«{out}»"
    return run


