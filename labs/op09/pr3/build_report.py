def table_for(limit):
    out = [["Вариант", "Операций деления", "Время, мс", "Ускорение"]]
    base = by[(limit, "v0")]["ms"]
    for v, label in [("v0", "Исходный"), ("v1", "Оптимизация 1"), ("v2", "Оптимизация 2"), ("v3", "Оптимизация 3 (решето)")]:
        r = by[(limit, v)]
        out.append([label, f"{r['divisions']:,}".replace(",", " "), fmt(r["ms"], 2), "1" if v == "v0" else times(base / r["ms"])])
    return out


def times(ratio):
    """«в 593 раза», «в 69 раз»: правильная форма слова «раз» после числа."""
    n = round(ratio)
    word = "раза" if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14) else "раз"
    return f"в {n} {word}"


def spaced(number):
    return f"{number:,}".replace(",", " ")


